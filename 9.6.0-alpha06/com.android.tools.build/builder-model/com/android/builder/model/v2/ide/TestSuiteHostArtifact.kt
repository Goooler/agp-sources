package com.android.builder.model.v2.ide

import com.android.builder.model.v2.AndroidModel
import com.android.builder.model.v2.models.HostJarTestSuiteSource
import com.android.builder.model.v2.models.SourceType

/**
 * Artifact for a [SourceType.HOST_JAR] source set of a test suite in a variant.
 *
 * There is one artifact per host jar source set of a test suite applied to the variant. It describes the compilation of that source set:
 * its generated source folders and classes folders contain the outputs of the tasks registered for the source set itself, such as source
 * generation, annotation processing, and Java and Kotlin compilation. When Android resources are enabled, the classes folders also contain
 * the compiled R class jar the source set is compiled against: either the R classes linked for the test suite itself, or those of the
 * tested variant.
 *
 * Sources and bytecode produced for the tested variant, such as BuildConfig, AIDL, and RenderScript sources generated by its build
 * features, or sources and bytecode registered through the legacy variant API, are excluded. They belong to the tested variant, and no task
 * generates them for the test suite source set.
 *
 * Like [JavaArtifact], there are no generated resource or asset folders: host jar source sets have no Android resource or asset sources of
 * their own. When the test suite enables Android resources, it uses the resources and assets of the tested variant, whose generated folders
 * are reported by [Variant.mainArtifact].
 *
 * @since 9.1
 */
interface TestSuiteHostArtifact : AbstractArtifact, AndroidModel {

  /** Name of the test suite this artifact belongs to. */
  val testSuiteName: String

  /** Name of the test suite source set this artifact is built from, matching [HostJarTestSuiteSource.name]. */
  val sourceSetName: String
}
