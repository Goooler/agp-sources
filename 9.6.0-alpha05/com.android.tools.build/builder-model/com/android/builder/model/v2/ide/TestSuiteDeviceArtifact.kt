package com.android.builder.model.v2.ide

import com.android.builder.model.v2.AndroidModel
import com.android.builder.model.v2.models.SourceType
import com.android.builder.model.v2.models.TestApkTestSuiteSource
import java.io.File

/**
 * Artifact for a [SourceType.TEST_APK] source set of a test suite in a variant.
 *
 * There is one artifact per test APK source set of a test suite applied to the variant. It describes the compilation of that source set:
 * its generated source folders and classes folders contain the outputs of the tasks registered for the source set itself, such as source
 * generation, annotation processing, and Java and Kotlin compilation. The classes folders also contain the compiled R class jar of the
 * tested variant when Android resources are enabled, because the source set is compiled against it.
 *
 * Sources and bytecode produced for the tested variant, such as BuildConfig, AIDL, and RenderScript sources generated by its build
 * features, or sources and bytecode registered through the legacy variant API, are excluded. They belong to the tested variant, and no task
 * generates them for the test suite source set.
 *
 * Unlike [AndroidArtifact], there are no generated resource or asset folders: test APK source sets only support a manifest, Java and Kotlin
 * sources, and Java resources, so no Android resources or assets are generated for them. The [SourceType.ASSETS] sources of a test suite
 * are separate test suite sources and are not part of this artifact.
 *
 * @since 9.1
 */
interface TestSuiteDeviceArtifact : AbstractArtifact, AndroidModel {

  /** Name of the test suite this artifact belongs to. */
  val testSuiteName: String

  /** Name of the test suite source set this artifact is built from, matching [TestApkTestSuiteSource.name]. */
  val sourceSetName: String

  /** The application ID of the test APK, or null if it cannot be computed. */
  val applicationId: String?

  /** The minimum SDK version of the test APK. */
  val minSdkVersion: ApiVersion

  /** Whether the test APK has a signing config that is ready to sign it. */
  val isSigned: Boolean

  /** The name of the signing config used to sign the test APK, or null if none. */
  val signingConfigName: String?

  /**
   * The redirect file pointing to the listing file that gets updated after each build with deployment-related information such as the
   * application ID and list of APKs, or null if no redirect file is registered for this component.
   */
  val assembleTaskOutputListingFile: File?
}
